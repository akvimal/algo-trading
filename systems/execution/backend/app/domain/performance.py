def _side(action) -> Optional[str]:
    a = (action or "").strip().upper()
    return "long" if a == "BUY" else "short" if a == "SELL" else None


def _reviewed(reviewed_at, notes) -> bool:
    return reviewed_at is not None or (notes is not None and notes.strip() != "")


def _f(value) -> Optional[float]:
    return float(value) if value is not None else None


def load_manual_trades(db: Session, user_id, segment: str, since: Optional[date] = None, book: str = "intraday") -> list[TradeRecord]:
    """The caller's own closed MANUAL trades for one segment (strategy_id IS
    NULL, the same "manual only" the frontend pages use): single positions that
    are not option legs, plus whole option groups. `since` (an IST date) drops
    trades that closed before it.

    `book` picks which of the user's two paper balances the trades belong to: 'intraday' (everything that is not a multi-day hold,
    the default) or 'positional' (spot holds with horizon='positional'; an option group is never positional)."""
    from app.domain.position_manager import load_settings  # local: position_manager is a heavy module and nothing else here needs it

    P, G = db_models.Position, db_models.OptionPositionGroup
    current_rate = load_settings(db, user_id).usdinr_rate if segment == "CRYPTO" else None

    def fx_of(row) -> float:
        if segment != "CRYPTO":
            return 1.0
        closed_at = getattr(row, "usdinr_at_close", None)
        rate = float(closed_at) if closed_at is not None else current_rate
        return rate if rate is not None else 1.0

    positional = book == "positional"
    positions = (
        db.query(P)
        .filter(
            P.user_id == user_id, P.strategy_id.is_(None), P.status == "CLOSED", P.segment == segment, P.option_group_id.is_(None), P.exit_time.isnot(None),
            P.horizon == "positional" if positional else P.horizon != "positional",
        )
        .all()
    )
    groups = (
        []
        if positional
        else db.query(G)
        .filter(G.user_id == user_id, G.strategy_id.is_(None), G.status == "CLOSED", G.segment == segment, G.exit_time.isnot(None))
        .all()
    )
    # A spread is live when any of its legs went to the broker.
    live_groups = (
        {leg.option_group_id for leg in db.query(P).filter(P.user_id == user_id, P.option_group_id.isnot(None), P.is_live_broker_order.is_(True)).all()}
        if groups
        else set()
    )
    records = [
        TradeRecord(
            segment=p.segment, symbol=p.symbol, pnl=_f(p.pnl), entry_price=_f(p.entry_price), stop_loss_price=_f(p.stop_loss_price),
            target_price=_f(p.target_price), quantity=_f(p.quantity), exit_time=p.exit_time, exit_reason=p.exit_reason,
            order_type=p.order_type, entry_setup_tag=p.entry_setup_tag, entry_confidence=p.entry_confidence, setup_tag=p.setup_tag,
            confidence=p.confidence, reviewed=_reviewed(p.reviewed_at, p.notes), auto_traded=bool(p.auto_traded),
            charges=_f(p.charges) or 0.0, slippage_cost=_f(p.slippage_cost) or 0.0, costs_applied=p.charges is not None,
            live=bool(p.is_live_broker_order), fx=fx_of(p),
            side=_side(getattr(p, "action", None)), exit_price=_f(getattr(p, "exit_price", None)), entry_time=getattr(p, "entry_time", None),
        )
        for p in positions
    ] + [
        TradeRecord(
            segment=g.segment, symbol=g.underlying_symbol, pnl=_f(g.pnl), entry_price=None, stop_loss_price=_f(g.spot_stop_loss_price),
            target_price=_f(g.spot_target_price), quantity=_f(g.quantity), exit_time=g.exit_time, exit_reason=g.exit_reason,
            order_type=g.order_type, entry_setup_tag=g.entry_setup_tag, entry_confidence=g.entry_confidence, setup_tag=g.setup_tag,
            confidence=g.confidence, reviewed=_reviewed(g.reviewed_at, g.notes), auto_traded=bool(g.auto_traded),
            charges=_f(g.charges) or 0.0, slippage_cost=_f(g.slippage_cost) or 0.0, costs_applied=g.charges is not None,
            live=g.id in live_groups, fx=fx_of(g),
            side=_side(getattr(g, "action", None)), entry_time=getattr(g, "created_at", None), label=getattr(g, "strategy_type", None),
        )
        for g in groups
    ]
    if since is not None:
        records = [r for r in records if day_key(r.exit_time) >= since]
    return records


def epoch_start(db: Session, account) -> Optional[date]:
    """The IST date of the account's latest reset marker (see equity_history.py),
    or None if it has never been reset."""
    S = db_models.AccountEquitySnapshot
    row = (
        db.query(S).filter(S.account_id == account.id, S.is_reset_point.is_(True)).order_by(S.snapshot_date.desc()).first()
    )
    return row.snapshot_date if row is not None else None
